package gitx

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/UseTrace-SI/trace-cli/internal/adapters/hookcmd"
)

const begin = "# trace post-commit begin\n"
const end = "# trace post-commit end\n"

// insertedMarker is recorded instead of a backup path when the Trace block was
// inserted into an existing shell hook rather than chained after renaming it.
const insertedMarker = "inserted"

// hookSpec describes one Git hook that Trace merges into.
type hookSpec struct {
	name, begin, end string
	body             func() string
	// chain runs the preserved original hook when it had to be renamed.
	chain string
}

var postCommitHook = hookSpec{
	name:  "post-commit",
	begin: begin,
	end:   end,
	body: func() string {
		// The block never exits: it may run before the rest of a user's hook.
		return "if trace_sha=$(git rev-parse HEAD 2>/dev/null); then\n" +
			"\tprintf '{\"git_sha\":\"%s\"}\\n' \"$trace_sha\" | " + hookcmd.Command("git", "git_commit") + " >/dev/null 2>&1 || true\n" +
			"fi\n"
	},
	chain: "if [ -x \"$0.pre-trace\" ]; then \"$0.pre-trace\" \"$@\"; fi\n",
}

// hookBlock renders the Trace-managed part of a hook. The executable is
// absolute so GUI Git clients with a minimal PATH still record commits.
func (h hookSpec) block() string { return h.begin + h.body() + h.end }

// ManualHookError reports that Git runs hooks from a directory inside the
// worktree (core.hooksPath). Those files are tracked project content or are
// generated by a hook manager such as husky, so Trace leaves them unchanged;
// Block is what to add to Path by hand.
type ManualHookError struct {
	Path  string
	Block string
}

func (e *ManualHookError) Error() string {
	return fmt.Sprintf("git hooks are managed in %s inside the repository; add the Trace block to %s yourself", filepath.Dir(e.Path), filepath.Base(e.Path))
}

func hookPaths(root, name string) (string, string, string, error) {
	p, err := GitPath(root, "hooks/"+name)
	if err != nil {
		return "", "", "", err
	}
	return p, filepath.Join(root, ".trace", name+"-original"), filepath.Join(root, ".trace", name+"-installed-sha"), nil
}
func hash(b []byte) string { h := sha256.Sum256(b); return hex.EncodeToString(h[:]) }

// InstallHook merges Trace's post-commit block into the repository's hook.
func InstallHook(root string) error { return installHook(root, postCommitHook) }

// UninstallHook removes what InstallHook added and restores the original hook.
func UninstallHook(root string) error { return uninstallHook(root, postCommitHook) }

func installHook(root string, h hookSpec) error {
	p, record, installedHash, err := hookPaths(root, h.name)
	if err != nil {
		return err
	}
	inWorktree, err := hookInWorktree(root, p)
	if err != nil {
		return err
	}
	if inWorktree {
		return &ManualHookError{Path: p, Block: h.block()}
	}
	current, err := os.ReadFile(p)
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	existed := err == nil
	if start := strings.Index(string(current), h.begin); start >= 0 {
		stop := strings.Index(string(current), h.end)
		if stop < start {
			return nil
		}
		stop += len(h.end)
		// Rewrite only the Trace block so hooks installed by older versions
		// pick up the absolute executable path.
		updated := append(append(append([]byte{}, current[:start]...), h.block()...), current[stop:]...)
		if string(updated) == string(current) {
			return nil
		}
		if err := os.WriteFile(p, updated, 0755); err != nil {
			return fmt.Errorf("updating %s hook: %w", h.name, err)
		}
		return os.WriteFile(installedHash, []byte(hash(updated)), 0600)
	}
	if existed && shellScript(current) {
		// Hook managers such as overcommit dispatch on "$0". Renaming the hook
		// would make them look up the wrong name, so insert the block instead.
		updated := insertAfterShebang(current, h.block())
		if err := os.WriteFile(p, updated, 0755); err != nil {
			return fmt.Errorf("updating %s hook: %w", h.name, err)
		}
		if err := os.WriteFile(record, []byte(insertedMarker), 0600); err != nil {
			return err
		}
		return os.WriteFile(installedHash, []byte(hash(updated)), 0600)
	}
	backup := ""
	if existed {
		backup = p + ".pre-trace"
		if _, err := os.Stat(backup); err == nil {
			return fmt.Errorf("existing %s backup blocks Trace installation: %s", h.name, backup)
		} else if !os.IsNotExist(err) {
			return err
		}
		if err := os.Rename(p, backup); err != nil {
			return fmt.Errorf("preserving %s hook: %w", h.name, err)
		}
	}
	var script strings.Builder
	script.WriteString("#!/bin/sh\n")
	if backup != "" {
		script.WriteString(h.chain)
	}
	script.WriteString(h.block())
	if err := os.MkdirAll(filepath.Dir(p), 0700); err != nil {
		return err
	}
	b := []byte(script.String())
	if err := os.WriteFile(p, b, 0755); err != nil {
		return fmt.Errorf("writing %s hook: %w", h.name, err)
	}
	if err := os.WriteFile(record, []byte(backup), 0600); err != nil {
		return err
	}
	return os.WriteFile(installedHash, []byte(hash(b)), 0600)
}

func uninstallHook(root string, h hookSpec) error {
	p, record, installedHash, err := hookPaths(root, h.name)
	if err != nil {
		return err
	}
	if inWorktree, err := hookInWorktree(root, p); err != nil || inWorktree {
		return err
	}
	current, err := os.ReadFile(p)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !strings.Contains(string(current), h.begin) {
		return nil
	}
	backupBytes, _ := os.ReadFile(record)
	backup := string(backupBytes)
	hashBytes, _ := os.ReadFile(installedHash)
	if hash(current) == string(hashBytes) && backup != insertedMarker {
		if err := os.Remove(p); err != nil {
			return err
		}
		if backup != "" {
			return os.Rename(backup, p)
		}
		return nil
	}
	start := strings.Index(string(current), h.begin)
	stop := strings.Index(string(current), h.end)
	if start < 0 || stop < start {
		return nil
	}
	stop += len(h.end)
	cleaned := append(append([]byte{}, current[:start]...), current[stop:]...)
	return os.WriteFile(p, cleaned, 0755)
}

// shellScript reports whether a hook is a POSIX-compatible shell script, into
// which the Trace block can be inserted.
func shellScript(b []byte) bool {
	line, _, _ := bytes.Cut(b, []byte("\n"))
	if !bytes.HasPrefix(line, []byte("#!")) {
		return false
	}
	fields := strings.Fields(string(line[2:]))
	if len(fields) == 0 {
		return false
	}
	interpreter := filepath.Base(fields[0])
	if interpreter == "env" {
		interpreter = ""
		for _, field := range fields[1:] {
			if !strings.HasPrefix(field, "-") {
				interpreter = filepath.Base(field)
				break
			}
		}
	}
	switch interpreter {
	case "sh", "bash", "dash", "zsh", "ksh", "ash", "mksh":
		return true
	}
	return false
}

func insertAfterShebang(b []byte, block string) []byte {
	i := bytes.IndexByte(b, '\n')
	if i < 0 {
		return append(append(append([]byte{}, b...), '\n'), block...)
	}
	return append(append(append([]byte{}, b[:i+1]...), block...), b[i+1:]...)
}

// hookInWorktree reports whether Git runs the hook from inside the worktree,
// outside the repository's Git directory (core.hooksPath pointing at project
// files). Hooks in the Git directory or in a directory outside the worktree,
// such as a user's hooks path, may be merged into.
func hookInWorktree(root, hookPath string) (bool, error) {
	out, err := exec.Command("git", "-C", root, "rev-parse", "--git-common-dir").Output()
	if err != nil {
		return false, fmt.Errorf("finding Git directory: %w", err)
	}
	common := strings.TrimSpace(string(out))
	if !filepath.IsAbs(common) {
		common = filepath.Join(root, common)
	}
	dir, err := existingPath(filepath.Dir(hookPath))
	if err != nil {
		return false, err
	}
	gitDir, err := existingPath(common)
	if err != nil {
		return false, err
	}
	worktree, err := existingPath(root)
	if err != nil {
		return false, err
	}
	return !within(gitDir, dir) && within(worktree, dir), nil
}

// existingPath resolves symlinks in the longest existing prefix of p.
func existingPath(p string) (string, error) {
	p, err := filepath.Abs(p)
	if err != nil {
		return "", err
	}
	var missing []string
	for {
		resolved, err := filepath.EvalSymlinks(p)
		if err == nil {
			for i := len(missing) - 1; i >= 0; i-- {
				resolved = filepath.Join(resolved, missing[i])
			}
			return resolved, nil
		}
		if !os.IsNotExist(err) {
			return "", err
		}
		parent := filepath.Dir(p)
		if parent == p {
			return "", err
		}
		missing = append(missing, filepath.Base(p))
		p = parent
	}
}

func within(parent, p string) bool {
	rel, err := filepath.Rel(parent, p)
	return err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}
